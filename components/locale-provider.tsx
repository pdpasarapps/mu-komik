type LocaleContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (text: string) => string;
};

const LocaleContext = createContext<LocaleContextValue | null>(null);

export function LocaleProvider({ initialLocale, children }: { initialLocale: Locale; children: ReactNode }) {
  const [locale, setLocaleState] = useState(initialLocale);

  useEffect(() => {
    document.documentElement.lang = locale === "id" ? "id" : "en";
  }, [locale]);

  const setLocale = useCallback((nextLocale: Locale) => {
    setLocaleState(nextLocale);
    const secure = window.location.protocol === "https:" ? "; Secure" : "";
    document.cookie = `mu-komik-locale=${nextLocale}; Path=/; Max-Age=31536000; SameSite=Lax${secure}`;
  }, []);

  const value = useMemo<LocaleContextValue>(() => ({
    locale,
    setLocale,
    t: (text) => locale === "en" ? translations[text] ?? text : text,
  }), [locale, setLocale]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  const context = useContext(LocaleContext);
  if (!context) throw new Error("useLocale must be used within LocaleProvider.");
  return context;
}

export function LanguageSwitcher() {
  const { locale, setLocale } = useLocale();
  const nextLocale = locale === "id" ? "en" : "id";
  const label = locale === "id" ? "Switch language to English" : "Ganti bahasa ke Indonesia";
  return (
    <button
      type="button"
      className="language-switcher"
      onClick={() => setLocale(nextLocale)}
      aria-label={label}
      title={label}
    >
      <Languages size={16} aria-hidden="true" />
      {nextLocale === "en" ? (
        <svg className="language-switcher-flag" viewBox="0 0 60 30" aria-hidden="true">
          <rect width="60" height="30" fill="#012169" />
          <path d="M0 0 60 30M60 0 0 30" stroke="#fff" strokeWidth="6" />
          <path d="M0 0 60 30M60 0 0 30" stroke="#c8102e" strokeWidth="2.5" />
          <path d="M30 0v30M0 15h60" stroke="#fff" strokeWidth="10" />
          <path d="M30 0v30M0 15h60" stroke="#c8102e" strokeWidth="6" />
        </svg>
      ) : (
        <svg className="language-switcher-flag" viewBox="0 0 60 30" aria-hidden="true">
          <rect width="60" height="15" fill="#ce1126" />
          <rect y="15" width="60" height="15" fill="#fff" />
        </svg>
      )}
      <span>{nextLocale.toUpperCase()}</span>
    </button>
  );
}
